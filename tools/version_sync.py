"""版本号同步/校验：`core/version.py` 是唯一真源。

用法：
    python tools/version_sync.py --write    # 生成派生文件
    python tools/version_sync.py --check    # 校验全部派生文件一致（CI/测试用）

派生目标：
  build/version_info.txt   PyInstaller 的 exe 版本资源（文件版本/产品版本）
  launcher/Version.g.cs    启动器 C# 常量（更新比对用）
  pyproject.toml           [project] version
"""
import argparse
import ast
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION_PY = os.path.join(ROOT, "core", "version.py")
VERSION_INFO = os.path.join(ROOT, "build", "version_info.txt")
LAUNCHER_CS = os.path.join(ROOT, "launcher", "Version.g.cs")
INSTALLER_ISS = os.path.join(ROOT, "installer", "version.iss")
PYPROJECT = os.path.join(ROOT, "pyproject.toml")
WEB_INDEX = os.path.join(ROOT, "web", "index.html")

COMPANY = "SJZ"
PRODUCT = "SJZ-Control"


def read_version():
    """从 core/version.py 取 APP_VERSION（AST 解析，不 import 重依赖）。"""
    tree = ast.parse(open(VERSION_PY, encoding="utf-8").read(), VERSION_PY)
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == "APP_VERSION":
                    return ast.literal_eval(node.value)
    raise SystemExit("core/version.py 里找不到 APP_VERSION")


def version_tuple(v):
    parts = [int(x) for x in re.findall(r"\d+", v.split("-")[0])]
    parts = (parts + [0, 0, 0, 0])[:4]
    return tuple(parts)


def version_info_text(v):
    q = version_tuple(v)
    return f"""# UTF-8
# 由 tools/version_sync.py 生成，不要手改。真源 core/version.py。
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={q},
    prodvers={q},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', '{COMPANY}'),
        StringStruct('FileDescription', '{PRODUCT}'),
        StringStruct('FileVersion', '{v}'),
        StringStruct('InternalName', '{PRODUCT}'),
        StringStruct('OriginalFilename', '{PRODUCT}.exe'),
        StringStruct('ProductName', '{PRODUCT}'),
        StringStruct('ProductVersion', '{v}')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def launcher_cs_text(v):
    return f"""// <auto-generated>
// 由 tools/version_sync.py 从 core/version.py 生成，不要手改。
namespace SjzLauncher
{{
    internal static class AppVersion
    {{
        public const string Current = "{v}";
    }}
}}
"""


def installer_iss_text(v):
    return ("// <auto-generated> 由 tools/version_sync.py 生成，不要手改。\n"
            f'#define MyAppVersion "{v}"\n')


# 派生文件清单：相对仓库根路径 -> 渲染函数。--write 与测试共用同一份清单，
# 避免“测试以为生成了 A、实际生成的是 B”这类漂移。
DERIVED = (
    ("build/version_info.txt", version_info_text),
    ("launcher/Version.g.cs", launcher_cs_text),
    ("installer/version.iss", installer_iss_text),
)


def render_all(v):
    """在内存里渲染全部派生文件（不落盘），供 --write 与测试临时目录复用。"""
    return {rel: fn(v) for rel, fn in DERIVED}


def _write_if_changed(path, text):
    """内容相同就不落盘：重复跑 --write 不改变 mtime，增量构建不会被误触发。"""
    if os.path.isfile(path):
        try:
            if open(path, encoding="utf-8").read() == text:
                return False
        except OSError:
            pass
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True


def write_all(v):
    for rel, text in render_all(v).items():
        _write_if_changed(os.path.join(ROOT, *rel.split("/")), text)

    src = open(PYPROJECT, encoding="utf-8").read()
    new = re.sub(r'(?m)^version\s*=\s*"[^"]*"', f'version = "{v}"', src, count=1)
    if new != src:
        with open(PYPROJECT, "w", encoding="utf-8", newline="\n") as f:
            f.write(new)


def check_all(v):
    """返回 (ok, 明细列表)。每条为 dict(name, ok, detail)。"""
    rows = []

    def add(name, ok, detail):
        rows.append({"name": name, "ok": bool(ok), "detail": detail})

    if not os.path.isfile(VERSION_INFO):
        add("build/version_info.txt", False, "缺失，先跑 --write")
    else:
        txt = open(VERSION_INFO, encoding="utf-8").read()
        ok = f"'{v}'" in txt and f"filevers={version_tuple(v)}" in txt
        add("build/version_info.txt", ok, f"声明版本 {v}")

    if not os.path.isfile(LAUNCHER_CS):
        add("launcher/Version.g.cs", False, "缺失，先跑 --write")
    else:
        txt = open(LAUNCHER_CS, encoding="utf-8").read()
        m = re.search(r'Current\s*=\s*"([^"]+)"', txt)
        got = m.group(1) if m else None
        add("launcher/Version.g.cs", got == v, f"Current={got}")

    m = re.search(r'(?m)^version\s*=\s*"([^"]+)"', open(PYPROJECT, encoding="utf-8").read())
    got = m.group(1) if m else None
    add("pyproject.toml", got == v, f"version={got}")

    if not os.path.isfile(INSTALLER_ISS):
        add("installer/version.iss", False, "缺失，先跑 --write")
    else:
        txt = open(INSTALLER_ISS, encoding="utf-8").read()
        m = re.search(r'#define\s+MyAppVersion\s+"([^"]+)"', txt)
        got = m.group(1) if m else None
        add("installer/version.iss", got == v, f"MyAppVersion={got}")

    # 关于页只能从接口读版本，不能写死字面量
    html = open(WEB_INDEX, encoding="utf-8").read()
    hard = re.findall(r"(?<![\w.])v?\d+\.\d+\.\d+(?![\w.])", html)
    add("web/index.html", not hard, "无硬编码版本号" if not hard else f"发现字面量 {hard[:5]}")

    # 关于页取值链路：S.config.version
    add("web 关于页取值", "S.config.version" in html, "从 /api/config 读取")

    # 服务端把版本注入 config 响应
    cfg = open(os.path.join(ROOT, "core", "config.py"), encoding="utf-8").read()
    add("core/config.public()", 'out["version"]' in cfg or '"version"' in cfg,
        "public() 注入 version")

    return all(r["ok"] for r in rows), rows


def main(argv=None):
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    v = read_version()
    if args.write:
        write_all(v)
        ok, rows = check_all(v)
    else:
        ok, rows = check_all(v)

    if args.json:
        print(json.dumps({"version": v, "ok": ok, "checks": rows}, ensure_ascii=False))
    else:
        print(f"版本真源 = {v}")
        for r in rows:
            print(("  OK   " if r["ok"] else "  FAIL ") + r["name"] + "  " + r["detail"])
        print("结果：" + ("一致" if ok else "不一致"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
