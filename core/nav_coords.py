class NavError(Exception):
    """导航失败。附带是哪一步失败的，方便日志定位。"""


def _scaled(point, screen_w, screen_h, base=(1920, 1080)):
    """把基准分辨率下的坐标等比缩放到当前屏幕。

    只做等比缩放，不做布局推断——窗口比例变了就必须重新标定。
    """
    x, y = point
    return (int(round(x * screen_w / base[0])),
            int(round(y * screen_h / base[1])))


# ---------------------------------------------------------------- 引擎用的归一化 ROI
#
# 引擎按**归一化比例**抓 ROI（换分辨率不用重配），导航按绝对像素。
# 两套坐标系都得有，但定义只允许有一处 —— 以前引擎里散着 9 个 /1920 的
# 常量，同一块界面在两处各写一遍：游戏改版要改两个地方，还容易只改一处。
# 这里统一收口，引擎只做 `from .nav_coords import N_XXX as XXX_N`。

_BASE_W, _BASE_H = 1920.0, 1080.0


def nbox(x, y, w, h):
    """基准分辨率下的像素框 → 归一化框（引擎抓 ROI 用）。"""
    return {"x": x / _BASE_W, "y": y / _BASE_H,
            "w": w / _BASE_W, "h": h / _BASE_H}


